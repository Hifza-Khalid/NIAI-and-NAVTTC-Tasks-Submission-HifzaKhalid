# Linux Commands - Practice

# pwd     - Shows the current working directory.
# cd      - Changes the current directory.
# ls      - Lists files and directories.
# cat     - Displays the contents of a file.
# sudo    - Runs a command with administrator privileges.
# man     - Displays the manual/help for a command.
# redirection - Sends command input or output to/from a file.
# mkdir   - Creates a new directory.
# rm      - Removes files or directories.
# rmdir   - Removes an empty directory.
# cp      - Copies files or directories.
# mv      - Moves or renames files and directories.
# file    - Identifies the type of a file.
# reading - Reads and displays file contents.
# more    - Displays file contents one screen at a time.
# less    - Displays and scrolls through file contents.
# head    - Displays the beginning of a file.
# alias   - Creates shortcuts for commands.
# shutdown - Shuts down the system.
# restart - Restarts the system.
# touch   - Creates a new empty file.
# nano    - Opens a simple text editor.
# bash    - Starts the Bash shell.
# sh      - Starts the standard shell.
# chmod   - Changes file permissions.
# ps      - Displays running processes.
# kill    - Terminates a running process.
# dpkg    - Manages Debian-based Linux packages.