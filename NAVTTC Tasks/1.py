# ------------------------------------------------------------
# TASK 1: Download and Install Anaconda3
# ------------------------------------------------------------
#
# Anaconda3 is a Python distribution used for Python
# programming, data science and machine learning.
#
# Steps:
# 1. Download Anaconda3 for Windows.
# 2. Run the Anaconda3 installer.
# 3. Select "Just Me" installation.
# 4. Complete the installation.
# 5. Open Anaconda Prompt.
# 6. Verify installation using:
#
#       conda --version
#
# ------------------------------------------------------------


# ------------------------------------------------------------
# TASK 2: Install PyTorch
# ------------------------------------------------------------
#
# PyTorch is a machine learning and deep learning framework.
#
# Open Anaconda Prompt and create a separate environment:
#
#       conda create -n pytorch python=3.11 -y
#
# Activate the environment:
#
#       conda activate pytorch
#
# Install PyTorch:
#
#       pip install torch torchvision
#
# Verify PyTorch:
#
#       python
#
#       import torch
#       print(torch.__version__)
#
# ------------------------------------------------------------


# ------------------------------------------------------------
# TASK 3: Install TensorFlow 2.0
# ------------------------------------------------------------
#
# TensorFlow is a machine learning and deep learning framework.
#
# TensorFlow 2.0 is an older version, so it should be installed
# in a separate compatible Python environment.
#
# Create the environment:
#
#       conda create -n tensorflow20 python=3.7 -y
#
# Activate the environment:
#
#       conda activate tensorflow20
#
# Install TensorFlow 2.0:
#
#       pip install tensorflow==2.0.0
#
# Verify TensorFlow:
#
#       python
#
#       import tensorflow as tf
#       print(tf.__version__)
#
# ------------------------------------------------------------


# ------------------------------------------------------------
# TASK 4: Download and Install Visual Studio Code (VS Code)
# ------------------------------------------------------------
#
# VS Code is a source-code editor used for Python programming.
#
# Steps:
# 1. Download VS Code for Windows.
# 2. Run the installer.
# 3. Complete the installation.
# 4. Open Visual Studio Code.
# 5. Install the Python extension from Microsoft.
#
# ------------------------------------------------------------


# ------------------------------------------------------------
# TASK 5: Download and Install PyCharm
# ------------------------------------------------------------
#
# PyCharm is an Integrated Development Environment (IDE)
# specially designed for Python programming.
#
# Steps:
# 1. Download PyCharm for Windows.
# 2. Run the installer.
# 3. Complete the installation.
# 4. Open PyCharm.
# 5. Create or open a Python project.
#
