# Demonstrate nested if statements

# Store a number
i = 10

# Check the first condition
if (i == 10):

    # Check if i is smaller than 15
    if (i < 15):
        print("i is smaller than 15")

    # Check if i is smaller than 12
    if (i < 12):
        print("i is smaller than 12 too")
    else:
        print("i is greater than 15")