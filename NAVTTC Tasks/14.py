# Check a value using if, elif and else

# Store a number
i = 20

# Check if i is 10
if (i == 10):
    print("i is 10")

# Check if i is 15
elif (i == 15):
    print("i is 15")

# Check if i is 20
elif (i == 20):
    print("i is 20")

# Run if none of the conditions match
else:
    print("i is not present")